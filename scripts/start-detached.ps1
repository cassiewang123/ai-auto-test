[CmdletBinding()]
param(
    [switch]$SkipFrontend,

    [ValidateRange(1024, 65535)]
    [int]$BackendPort = 8001,

    [ValidateRange(15, 300)]
    [int]$WaitSeconds = 120
)

# 以「脱离当前终端/会话」的方式启动 AIRETEST 前后端。
#
# scripts/start-local.ps1 用 Start-Process 启动，进程仍是当前进程树的子进程：
# 关掉终端、或宿主清理任务时，服务会被一并结束。本脚本改用 WMI
# (Win32_Process.Create) 拉起 .runtime\start-*.cmd，父进程是 WmiPrvSE，
# 因此终端关闭、代理会话结束后服务仍然存活。
#
# 用法：
#   powershell -File scripts\start-detached.ps1
#   powershell -File scripts\start-detached.ps1 -SkipFrontend
# 停止：scripts\stop-detached.ps1

Set-StrictMode -Version 2.0
$ErrorActionPreference = "Stop"
. (Join-Path $PSScriptRoot "local-runtime.ps1")

$projectRoot = Get-AiretestProjectRoot
$runtimeDir = Join-Path $projectRoot ".runtime"
$logDir = Join-Path $runtimeDir "logs"
New-Item -ItemType Directory -Path $logDir -Force | Out-Null

function Start-DetachedLauncher {
    param(
        [Parameter(Mandatory = $true)][string]$Launcher,
        [Parameter(Mandatory = $true)][string]$WorkingDirectory,
        [Parameter(Mandatory = $true)][string]$DisplayName
    )
    if (-not (Test-Path -LiteralPath $Launcher -PathType Leaf)) {
        throw "未找到启动脚本：$Launcher"
    }
    $commandLine = 'cmd.exe /c "{0}"' -f $Launcher
    $result = Invoke-CimMethod -ClassName Win32_Process -MethodName Create `
        -Arguments @{ CommandLine = $commandLine; CurrentDirectory = $WorkingDirectory }
    if ($result.ReturnValue -ne 0) {
        throw "$DisplayName 启动失败（Win32_Process.Create 返回 $($result.ReturnValue)）"
    }
    Write-Host "$DisplayName 启动中，PID：$($result.ProcessId)"
}

$pythonPath = Resolve-AiretestPython

# 后端启动脚本里写死了 pythonw 路径，这里按当前解析结果重写一份，避免换机器后失效
$pythonwPath = Join-Path (Split-Path -Parent $pythonPath) "pythonw.exe"
if (-not (Test-Path -LiteralPath $pythonwPath -PathType Leaf)) {
    $pythonwPath = $pythonPath
}
$backendLauncher = Join-Path $runtimeDir "start-backend.cmd"
$backendLauncherContent = @"
@echo off
rem Auto-generated by scripts\start-detached.ps1 - safe to overwrite.
cd /d $projectRoot
"$pythonwPath" backend\run_server.py >> .runtime\logs\backend.out.log 2>> .runtime\logs\backend.err.log
"@
Set-Content -LiteralPath $backendLauncher -Value $backendLauncherContent -Encoding ascii

if (-not (Test-AiretestPortInUse -Port $BackendPort)) {
    Start-DetachedLauncher -Launcher $backendLauncher `
        -WorkingDirectory $projectRoot -DisplayName "后端"
}
else {
    Write-Host "后端端口 $BackendPort 已在监听，跳过启动。"
}

if (-not (Wait-AiretestHttp -Uri "http://127.0.0.1:$BackendPort/health/ready" `
    -TimeoutSeconds $WaitSeconds)) {
    $tail = if (Test-Path -LiteralPath (Join-Path $logDir "backend.err.log")) {
        (Get-Content -LiteralPath (Join-Path $logDir "backend.err.log") -Tail 20 `
            -ErrorAction SilentlyContinue) -join [Environment]::NewLine
    }
    else { "" }
    throw "后端未在 $WaitSeconds 秒内就绪。$([Environment]::NewLine)$tail"
}

if (-not $SkipFrontend) {
    $nodePath = Resolve-AiretestNode -PythonPath $pythonPath
    $frontendDir = Join-Path $projectRoot "frontend"
    $frontendLauncher = Join-Path $runtimeDir "start-frontend.cmd"
    $frontendLauncherContent = @"
@echo off
rem Auto-generated by scripts\start-detached.ps1 - safe to overwrite.
cd /d $frontendDir
"$nodePath" node_modules\vite\bin\vite.js --host 127.0.0.1 --port 5173 --strictPort >> ..\.runtime\logs\frontend.out.log 2>> ..\.runtime\logs\frontend.err.log
"@
    Set-Content -LiteralPath $frontendLauncher -Value $frontendLauncherContent -Encoding ascii

    if (-not (Test-AiretestPortInUse -Port 5173)) {
        Start-DetachedLauncher -Launcher $frontendLauncher `
            -WorkingDirectory $frontendDir -DisplayName "前端"
    }
    else {
        Write-Host "前端端口 5173 已在监听，跳过启动。"
    }

    if (-not (Wait-AiretestHttp -Uri "http://127.0.0.1:5173" `
        -TimeoutSeconds $WaitSeconds)) {
        throw "前端未在 $WaitSeconds 秒内就绪，请检查 .runtime\logs。"
    }
}

Write-Host ""
Write-Host "AIRETEST 已以后台方式启动（关闭终端不会停止服务）："
Write-Host "  前端：http://localhost:5173"
Write-Host "  后端：http://localhost:$BackendPort"
Write-Host "  API 文档：http://localhost:$BackendPort/docs"
Write-Host "  日志：$logDir"
